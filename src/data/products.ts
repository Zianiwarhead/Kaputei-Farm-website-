export interface VariantPrice {
  /** Exact variant name as it appears in `variants`, if the product has variants */
  variant?: string
  /** Exact size as it appears in `sizes` */
  size: string
  priceKes: number
  compareAtPriceKes?: number | null
  /** Local or remote image for this exact variant+size combo. Falls back to product.images[0] */
  image?: string
}

